#  4(x − 2) + 3 = 2x + 7
# 
# step 1 - simplify the left side of the equation so 4x - 8 +3 or 4x -5
# step 2 - we can add 5 to each side so 4x = 2x + 12
# step 3 - isolate x so we get x = 6

def check_solution(x):
    if 4 * (x - 2) + 3 == 2 * x + 7:
        print('true')
        return True

check_solution(6)

